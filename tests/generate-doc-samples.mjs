/**
 * Generate sample documents from the Document Kit plugins into a folder, so you can
 * open them in real apps (Preview, Excel, PowerPoint/Keynote, LibreOffice) and check
 * the formats. Usage: node tests/generate-doc-samples.mjs [outputDir]
 */
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawn } from "node:child_process";
import { fileURLToPath } from "node:url";

const repoRoot = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.resolve(process.argv[2] ?? path.join(os.tmpdir(), "xtrac-doc-samples"));
// Footgun guard: this script rm -rf's its target before generating — refuse anything
// outside the OS temp dir (accept both the /tmp and realpath spellings on macOS).
const tmpReal = fs.realpathSync(os.tmpdir());
if (!out.startsWith(tmpReal + path.sep) && !out.startsWith(os.tmpdir() + path.sep)) {
  console.error(`Refusing: output must be inside the OS temp dir (got ${out}). Pass a path under ${tmpReal}.`);
  process.exit(1);
}
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });

function client(serverDir) {
  const child = spawn("node", [path.join(repoRoot, "plugins", serverDir, "server.mjs")], { cwd: out, stdio: ["pipe", "pipe", "ignore"] });
  let buffer = "";
  const pending = new Map();
  let nextId = 1;
  child.stdout.setEncoding("utf8");
  child.stdout.on("data", (chunk) => {
    buffer += chunk;
    let i;
    while ((i = buffer.indexOf("\n")) >= 0) {
      const line = buffer.slice(0, i).trim();
      buffer = buffer.slice(i + 1);
      try {
        const msg = JSON.parse(line);
        if (typeof msg.id === "number" && pending.has(msg.id)) {
          pending.get(msg.id)(msg);
          pending.delete(msg.id);
        }
      } catch {
        /* ignore */
      }
    }
  });
  const request = (method, params) =>
    new Promise((resolve) => {
      const id = nextId++;
      pending.set(id, resolve);
      child.stdin.write(JSON.stringify({ jsonrpc: "2.0", id, method, params }) + "\n");
    });
  return { request, stop: () => child.kill() };
}

async function withClient(dir, fn) {
  const c = client(dir);
  await c.request("initialize", { protocolVersion: "2024-11-05", capabilities: {}, clientInfo: { name: "samples" } });
  try {
    return await fn(c);
  } finally {
    c.stop();
  }
}

const resultText = (r) => r?.result?.content?.[0]?.text ?? "(no output)";

// ---- doc-text ----
await withClient("doc-text", async (c) => {
  const md = await c.request("tools/call", {
    name: "write_markdown",
    arguments: {
      path: "sample-report.md",
      title: "Quarterly Report",
      content: "## Highlights\n\n- Revenue **up 12%** quarter over quarter\n- Shipped the new *local-only* agent features\n- Zero security incidents\n\n## Details\n\n| Area | Status |\n| --- | --- |\n| Skills | shipped |\n| Plugins | shipped |\n| Hardening | shipped |\n\nAll work was verified with `npm test`.",
    },
  });
  console.log("md:", resultText(md));
  const html = await c.request("tools/call", {
    name: "write_html",
    arguments: { path: "sample-report.html", title: "Quarterly Report", content: "## Highlights\n\nRevenue **up 12%**.\n\n> Local-only. No cloud.\n\n- Skills shipped\n- Plugins shipped" },
  });
  console.log("html:", resultText(html));
});

